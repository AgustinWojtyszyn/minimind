"""Generate the Cloudflare prompt module from the canonical BoitIA policy."""
import json
from pathlib import Path
import sys
ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT))
from boitia.config import SYSTEM_PROMPT, PROMPT_VERSION

def main():
    out=ROOT/"deploy/cloudflare/prompt.mjs"
    out.write_text("// Generated by scripts/build_cloudflare.py; do not hand-edit.\n"
                   +"export const SYSTEM_PROMPT = "+json.dumps(SYSTEM_PROMPT,ensure_ascii=False)+";\n"
                   +"export const PROMPT_VERSION = "+json.dumps(PROMPT_VERSION)+";\n")

if __name__=="__main__":main()
